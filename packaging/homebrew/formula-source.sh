#!/usr/bin/env bash
# Prints the Homebrew formula that builds one clif release from source.
#
#   packaging/homebrew/formula-source.sh <version> [<tarball>]
#
# The source is the release's clif-<version>-source.tar.gz, which the release
# workflow makes with git archive and attaches beside the binaries: GitHub's
# generated tag archives have changed their bytes before, which breaks a
# pinned sha256. A release made before that asset existed falls back to the
# tag archive, with a warning. <tarball> is that asset already downloaded;
# without one the script downloads it to take its checksum. Either way the
# archive must hold clif-<version>/, so another tag's cannot be published
# under this one's name.
#
# The tap publishes it as clif-source beside the prebuilt clif
# (formula.sh). It is the formula homebrew-core would take, which accepts
# only source builds: renaming the class to Clif and dropping conflicts_with
# is the whole difference. It has no CFLint inside: a release embeds CFLint's
# prebuilt binary (-tags cflint_embed), and a source formula should not ship
# one, so clif uses a cflint on PATH, or downloads the pinned one on first
# use. It builds with Homebrew's go, so it builds only once that is at least
# go.mod's go line; the package-managers workflow builds and tests it, and
# publishes it only when that passes.
set -euo pipefail

version="${1:?usage: formula-source.sh <version> [<tarball>]}"
version="${version#v}"
url="https://github.com/cfmleditor/clif/releases/download/v${version}/clif-${version}-source.tar.gz"
tarball="${2:-}"

# shellcheck source=../../scripts/lib/sha256.sh
. "$(dirname "$0")/../../scripts/lib/sha256.sh"

if [ -z "${tarball}" ]; then
	tmp="$(mktemp -d)"
	trap 'rm -rf "$tmp"' EXIT
	tarball="${tmp}/clif-${version}-source.tar.gz"

	# Only a release without the asset (made before it existed) falls back;
	# any other failure stops here rather than pin the unstable tag archive.
	status="$(curl -sL --retry 3 -o "${tarball}" -w '%{http_code}' "${url}" || true)"
	case "${status}" in
	200) ;;
	404)
		url="https://github.com/cfmleditor/clif/archive/refs/tags/v${version}.tar.gz"
		echo "formula-source: v${version} has no source asset; using the tag archive, whose bytes GitHub may change" >&2
		curl -fsSL --retry 3 -o "${tarball}" "${url}"
		;;
	*)
		echo "formula-source: downloading ${url} failed (HTTP ${status:-none})" >&2
		exit 1
		;;
	esac
fi
[ -f "${tarball}" ] || { echo "missing ${tarball}" >&2; exit 1; }

# head closing the pipe early ends tar with SIGPIPE, which pipefail would
# otherwise make fatal.
top="$(tar -tzf "${tarball}" | head -1 || true)"
if [ "${top%%/*}" != "clif-${version}" ]; then
	echo "formula-source: ${tarball} holds ${top%%/*}/, not clif-${version}/" >&2
	exit 1
fi

cat <<FORMULA
# Generated by packaging/homebrew/formula-source.sh in cfmleditor/clif for
# each release. Edit that script, not this file.
class ClifSource < Formula
  desc "CFML language server and command-line checks (built from source)"
  homepage "https://github.com/cfmleditor/clif"
  url "${url}"
  sha256 "$(sha256 "${tarball}")"
  license "MIT"
  head "https://github.com/cfmleditor/clif.git", branch: "main"

  depends_on "go" => :build

  conflicts_with "clif", because: "both install \`clif\` and \`cfmleditor-lsp\` binaries"

  def install
    ENV["CGO_ENABLED"] = "1"
    system "go", "build", *std_go_args(ldflags: "-X main.version=#{version}", output: bin/"clif"), "./cmd/clif"
    bin.install_symlink "clif" => "cfmleditor-lsp"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/clif version")

    # Formatting goes through the tree-sitter grammar, so this checks the
    # CGO half of the build as well as the binary.
    (testpath/"t.cfm").write "<cfset x = 1>\n"
    assert_match "<cfset x = 1", shell_output("#{bin}/clif format #{testpath}/t.cfm")
  end
end
FORMULA
